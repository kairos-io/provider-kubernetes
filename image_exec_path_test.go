package main

// image_exec_path_test.go binds the build-time exec-path settings (ADR-19 U1,
// F-UNITPATH) to the Go source of truth, so a hand edit of either file cannot
// drift from internal/hostexec.
//
//   - the two systemd drop-ins the Dockerfile installs under
//     /usr/lib/systemd/system/<unit>.d/ must set exactly the reviewed directives,
//     and the PATH one must be hostexec.ChildPATH;
//   - containerd/config.toml must pin the shim, the runc binary and the three
//     directories containerd would otherwise execute from the Kairos-persistent
//     /opt, disable the plugins that look up a name the image does not ship, and
//     every path value must be an absolute path inside the read-only image.
//
// The TOML is read with an exact-line parser rather than a TOML library: the
// shipped file is generated by nothing and rewritten in one place only (the
// Dockerfile's sandbox_image sed), so a value that a real parser would accept but
// a human would misread -- a second assignment, a value spread over lines, a
// trailing comment -- is a finding, not something to normalize away. It mirrors
// parseSandboxImage in test/e2e/bundled_images.go and parse_sandbox_image in
// scripts/verify-bundle-refs.sh; scripts/verify-image-files.sh asserts the same
// lines against the SHIPPED image.

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path"
	"slices"
	"strconv"
	"strings"
	"testing"

	"github.com/kairos-io/provider-kubernetes/internal/hostexec"
)

