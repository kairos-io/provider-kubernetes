	containerdDropInSource      = "usr-lib-systemd/containerd.service.d/50-provider-kubernetes-exec-path.conf"
	kubeletDropInSource         = "usr-lib-systemd/kubelet.service.d/50-provider-kubernetes-exec-path.conf"
	containerdDropInImagePath   = "/usr/lib/systemd/system/containerd.service.d/50-provider-kubernetes-exec-path.conf"
	kubeletDropInImagePath      = "/usr/lib/systemd/system/kubelet.service.d/50-provider-kubernetes-exec-path.conf"
	imageVerifierBinDir         = "/usr/lib/containerd/image-verifier/bin"
	nriPluginPath               = "/usr/lib/nri/plugins"
	containerdShimPath          = "/usr/bin/containerd-shim-runc-v2"
	runcPath                    = "/usr/bin/runc"
	optPluginURI                = "io.containerd.internal.v1.opt"
	erofsDifferURI              = "io.containerd.differ.v1.erofs"
	erofsSnapshotterURI         = "io.containerd.snapshotter.v1.erofs"
	criRuncTable                = `plugins."io.containerd.grpc.v1.cri".containerd.runtimes.runc`
	criRuncOptionsTable         = criRuncTable + ".options"
	imageVerifierBindirTable    = `plugins."io.containerd.image-verifier.v1.bindir"`
	nriTable                    = `plugins."io.containerd.nri.v1.nri"`
	asciiSpace                  = " \t\n\v\f\r"
